#!/usr/bin/env bash
# Regenerates ../nanovg_vk_shaders.h (SPIR-V words of nanovg_vk.vert/.frag).
# Needs glslangValidator (and optionally spirv-val) on PATH.
set -euo pipefail
cd "$(dirname "$0")"
out=../nanovg_vk_shaders.h
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
glslangValidator -V --target-env vulkan1.0 --vn nvgvk_vert_spv -o "$tmp/vert.h" nanovg_vk.vert >/dev/null
glslangValidator -V --target-env vulkan1.0 --vn nvgvk_frag_spv -o "$tmp/frag.h" nanovg_vk.frag >/dev/null
if command -v spirv-val >/dev/null; then
	glslangValidator -V --target-env vulkan1.0 -o "$tmp/vert.spv" nanovg_vk.vert >/dev/null
	glslangValidator -V --target-env vulkan1.0 -o "$tmp/frag.spv" nanovg_vk.frag >/dev/null
	spirv-val --target-env vulkan1.0 "$tmp/vert.spv"
	spirv-val --target-env vulkan1.0 "$tmp/frag.spv"
fi
{
	echo "// Generated by shaders/gen_shaders.sh from shaders/nanovg_vk.vert and"
	echo "// shaders/nanovg_vk.frag. Do not edit; rerun the script."
	echo "#pragma once"
	echo "#include <stdint.h>"
	sed -e 's/^const uint32_t/static const uint32_t/' "$tmp/vert.h" | grep -v -e "^\s*//" -e "#pragma once"
	sed -e 's/^const uint32_t/static const uint32_t/' "$tmp/frag.h" | grep -v -e "^\s*//" -e "#pragma once"
} > "$out"
echo "wrote $out"
